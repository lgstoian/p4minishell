"""host_gen_runner.py - generate the host runner from the manifest.

`tools/host_test_manifest.json` names the shared test sources that run on the
host. This script turns that list into `test/host/main/host_main.c` (externs +
RUN_TEST calls + the completion markers) and records the resulting case count
as `expected_cases` in the manifest. Nothing else is generated.

The point is anti-drift: `tools/host_unit_run.py --static` re-runs this
generator in --check mode, so the committed runner, the manifest and the case
count can never disagree.

Usage:
  python tools/host_gen_runner.py            # rewrite runner + manifest
  python tools/host_gen_runner.py --check    # exit 1 if either is stale
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEST_DIR = os.path.join(ROOT, "test", "main")
HOST_MAIN = os.path.join(ROOT, "test", "host", "main", "host_main.c")
MANIFEST = os.path.join(ROOT, "tools", "host_test_manifest.json")

CASE = re.compile(r"^void\s+(test_[A-Za-z0-9_]+)\s*\(\s*void\s*\)", re.MULTILINE)

HEADER = '''/*
 * SPDX-FileCopyrightText: 2026 Stoian Alexandru
 * SPDX-License-Identifier: MIT
 */
/**
 * @file host_main.c
 * @brief Unity entry point for the host unit-test lane (GENERATED).
 *
 * Generated by tools/host_gen_runner.py from tools/host_test_manifest.json.
 * Do not edit by hand: add a test source to the manifest's "tests" list and
 * re-run the generator.
 *
 * Runs the pure-logic suites from test/main/ as a native executable built
 * with ESP-IDF's "linux" target. The cases are the same sources the
 * on-target test app runs; nothing here touches hardware, LVGL, the SD card
 * or any board peripheral.
 *
 * Output matches tools/unit_run.py's parser contract on purpose: Unity's own
 * "N Tests M Failures K Ignored" line, then "=== All tests completed ===".
 * A missing marker is a failure.
 *
 * This lane is a pre-gate, never a substitute for the on-target suite
 * (harness.md §0). A host pass says nothing about hardware behaviour.
 *
 * @module test/host
 * @layer test
 * @domain testing
 * @provides Host Unity runner (native, no hardware)
 * @status active
 * @test tools/host_unit_run.py
 * @hard-rule pure logic only - no display, storage, USB, radio or LVGL
 */

#include <stdio.h>
#include <stdlib.h>

#include "unity.h"
'''


def cases_for(name: str) -> list:
    path = os.path.join(TEST_DIR, name)
    if not os.path.isfile(path):
        raise SystemExit("host_gen_runner: missing test source: %s" % name)
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return CASE.findall(fh.read())


def render(manifest: dict) -> tuple:
    groups = []
    total = 0
    for name in manifest["tests"]:
        cases = cases_for(name)
        if not cases:
            raise SystemExit("host_gen_runner: no cases found in %s" % name)
        groups.append((name, cases))
        total += len(cases)

    out = [HEADER]
    for name, cases in groups:
        out.append("\n/* --- %s %s */" % (name, "-" * max(3, 56 - len(name))))
        for case in cases:
            out.append("extern void %s(void);" % case)

    out.append("\nvoid app_main(void)")
    out.append("{")
    out.append("    int failures;")
    out.append("")
    out.append("    /* The run is piped through the harness, so never let stdout sit in a")
    out.append("     * block buffer: a hang would look like \"no output at all\". */")
    out.append("    setvbuf(stdout, NULL, _IONBF, 0);")
    out.append("")
    out.append("    printf(\"\\n=== P4MiniShell Host Unit Tests ===\\n\\n\");")
    out.append("")
    out.append("    UNITY_BEGIN();")
    for name, cases in groups:
        out.append("")
        out.append("    /* %s */" % name)
        for case in cases:
            out.append("    RUN_TEST(%s);" % case)

    out.append("")
    out.append("    failures = UNITY_END();")
    out.append("")
    out.append("    printf(\"\\n=== All tests completed ===\\n\");")
    out.append("")
    out.append("    /* The linux target keeps the FreeRTOS scheduler and the esp_timer")
    out.append("     * service task alive, so a plain return from app_main would leave the")
    out.append("     * process running forever. Exit explicitly with the failure count. */")
    out.append("    fflush(stdout);")
    out.append("    exit(failures == 0 ? 0 : 1);")
    out.append("}")
    out.append("")
    return "\n".join(out), total


def main() -> int:
    check = "--check" in sys.argv[1:]
    with open(MANIFEST, "r", encoding="utf-8-sig") as fh:
        manifest = json.load(fh)

    text, total = render(manifest)
    manifest["expected_cases"] = total
    rendered_manifest = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"

    with open(HOST_MAIN, "r", encoding="utf-8") as fh:
        current_main = fh.read()
    with open(MANIFEST, "r", encoding="utf-8-sig") as fh:
        current_manifest = fh.read()

    stale = []
    if current_main != text:
        stale.append(HOST_MAIN)
    if current_manifest != rendered_manifest:
        stale.append(MANIFEST)

    if check:
        for path in stale:
            print("host_gen_runner: stale (re-run without --check): %s"
                  % os.path.relpath(path, ROOT))
        if stale:
            return 1
        print("host_gen_runner: up to date (%d cases)" % total)
        return 0

    with open(HOST_MAIN, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered_manifest)
    print("host_gen_runner: wrote %s (%d cases)"
          % (os.path.relpath(HOST_MAIN, ROOT), total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
